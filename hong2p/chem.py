def draw_molecule(cid: int, output_name: Optional[str] = None,
    output_dir: Optional[Path] = None, *, chemfig_output_dir: Optional[Path] = None,
    ignore_cache: bool = False, verbose: bool = False, **kwargs) -> None:
    """Renders 2D structure of PubChem `cid` to a PDF, via chemfig + LaTeX.

    Args:
        cid: PubChem CID

        output_name: basename (w/o extension) for output .tex/.pdf files. defaults to
            `str(cid)`.

        output_dir: directory to write standalone .tex and compiled PDF to. defaults to
            current directory.

        chemfig_output_dir: if None, also writes just the chemfig TeX to
            `<output_dir>/chemfig/<output_name>.tex`. if passed, the chemfig TeX is
            currently not written anywhere.

        ignore_cache: passed to `cid2chemfig_tex`

        verbose: if True, prints generated TeX and paths of files being written

        **kwargs: passed to `chemfig_standalone_tex`
    """
