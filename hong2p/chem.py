    if output_name is None:
        # TODO need to manually append '.pdf' (for latex output)?
        output_name = f'{cid}'

    chemfig_tex = cid2chemfig_tex(cid, ignore_cache=ignore_cache)
    tex = chemfig_standalone_tex(chemfig_tex, **kwargs)

    if verbose:
        print('chemfig_tex:')
