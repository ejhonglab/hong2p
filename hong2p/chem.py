    mol2chemfig_sty = hong2p_pkg_path / 'mol2chemfig.sty'
    assert mol2chemfig_sty.exists(), f'{mol2chemfig_sty=} did not exist!'

    # TODO TODO how to handle mol2chemfig.sty path? how to pass to compile_latex?
